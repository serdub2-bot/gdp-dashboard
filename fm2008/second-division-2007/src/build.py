def main() -> None:
    DATA.mkdir(parents=True, exist_ok=True)

    rows = []
    for zone, teams in SECOND.items():
        for pos, club, city in teams:
            rows.append({"zone": zone, "position": pos, "club": club,
                         "city": city, "full": club if club.lower() == city.lower()
                         else f"{club} {city}"})
    with (DATA / "second_division_2007.csv").open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=["zone", "position", "club", "city", "full"])
        w.writeheader()
        w.writerows(rows)

    first = [{"position": pos, "club": club, "city": city,
              "full": club if club.lower() == city.lower() else f"{club} {city}"}
             for pos, club, city in FIRST]
    with (DATA / "first_division_2007.csv").open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=["position", "club", "city", "full"])
        w.writeheader()
        w.writerows(first)

    print(f"second_division_2007.csv: {len(rows)} клубов, зон {len(SECOND)}")
    for zone, teams in SECOND.items():
        print(f"  {zone}: {len(teams)}")
    print(f"first_division_2007.csv: {len(first)} клубов")


if __name__ == "__main__":
    main()
