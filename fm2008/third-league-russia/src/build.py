WITHDRAWN = {"Гусев", "Квант", "Терек-2", "Альянс-2"}


def main() -> None:
    DATA.mkdir(parents=True, exist_ok=True)
    rows = []
    for zone, sub, teams in ZONES:
        for place, club, city in teams:
            rows.append({
                "zone": zone,
                "subzone": sub,
                "position": place,
                "club": club,
                "city": city,
                "status": "снялась" if club in WITHDRAWN else "участник",
            })

    with (DATA / "clubs_2007.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=["zone", "subzone", "position", "club", "city", "status"])
        w.writeheader()
        w.writerows(rows)

    zones = {}
    for zone, sub, teams in ZONES:
        z = zones.setdefault(zone, {"subzones": {}, "teams": 0})
        active = [t for t in teams if t[1] not in WITHDRAWN]
        z["teams"] += len(teams)
        z["subzones"][sub or "—"] = len(teams)
    structure = {
        "season": 2007,
        "competition": "Третья лига России (Первенство ЛФЛ, III дивизион)",
        "level": 4,
        "nation": "Россия",
        "source": "ru.wikipedia.org — Любительская футбольная лига 2007",
        "final_tournament": {
            "host_city": "Дзержинск",
            "dates": "13–21 октября 2007",
            "winner": "Химик (Дзержинск)",
            "runner_up": "Распадская (Междуреченск)",
            "third": "Истра",
        },
        "zones": zones,
        "total_rows": len(rows),
    }
    (DATA / "zones_2007.json").write_text(
        json.dumps(structure, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )

    lines = ["# Сводка по зонам (сезон 2007)", ""]
    lines += ["| Зона | Подзона | Команд |", "|---|---|---|"]
    for zone, sub, teams in ZONES:
        lines.append(f"| {zone} | {sub or '—'} | {len(teams)} |")
    lines += ["", f"Всего строк: **{len(rows)}** "
                  f"(включая снявшиеся: {', '.join(sorted(WITHDRAWN))}).", ""]
    (DATA / "README.md").write_text("\n".join(lines), encoding="utf-8")

    print(f"clubs_2007.csv: {len(rows)} строк")
    print(f"зон: {len(zones)}")


if __name__ == "__main__":
    main()
